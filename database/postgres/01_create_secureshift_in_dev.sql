-- A link "source needs target". Source and target can each be an application OR a component.
CREATE TABLE dev."Dependencies" (
    "DependencyId"  INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Dependencies" PRIMARY KEY,
    "Code"          VARCHAR(20)  GENERATED ALWAYS AS ('DEP-' || RIGHT('000' || CAST("DependencyId" AS VARCHAR(10)), 3)) STORED,
    "EnterpriseId"  INTEGER      NOT NULL CONSTRAINT "FK_Deps_Ent" REFERENCES dev."Enterprises" ("EnterpriseId"),
    "SourceApplicationId" INTEGER NULL CONSTRAINT "FK_Deps_SrcApp"  REFERENCES dev."Applications" ("ApplicationId"),
    "SourceComponentId"   INTEGER NULL CONSTRAINT "FK_Deps_SrcComp" REFERENCES dev."Components" ("ComponentId"),
    "TargetApplicationId" INTEGER NULL CONSTRAINT "FK_Deps_TgtApp"  REFERENCES dev."Applications" ("ApplicationId"),
    "TargetComponentId"   INTEGER NULL CONSTRAINT "FK_Deps_TgtComp" REFERENCES dev."Components" ("ComponentId"),
    "Criticality"   VARCHAR(10)  NOT NULL CONSTRAINT "CK_Deps_Crit" CHECK ("Criticality" IN ('Low', 'Medium', 'High', 'Critical')),
    "Description"   VARCHAR(200) NULL,
    "CreatedBy"     INTEGER      NULL CONSTRAINT "FK_Deps_Users" REFERENCES dev."Users" ("UserId"),
    -- exactly one source and exactly one target
    CONSTRAINT "CK_Deps_OneSource" CHECK (("SourceApplicationId" IS NOT NULL AND "SourceComponentId" IS NULL) OR
                                          ("SourceApplicationId" IS NULL AND "SourceComponentId" IS NOT NULL)),
    CONSTRAINT "CK_Deps_OneTarget" CHECK (("TargetApplicationId" IS NOT NULL AND "TargetComponentId" IS NULL) OR
                                          ("TargetApplicationId" IS NULL AND "TargetComponentId" IS NOT NULL)),
    -- not linked to itself
    CONSTRAINT "CK_Deps_NotSelf" CHECK (COALESCE("SourceApplicationId", -1) <> COALESCE("TargetApplicationId", -2)
                                    AND COALESCE("SourceComponentId", -1)   <> COALESCE("TargetComponentId", -2))
);
-- SQL Server treats NULLs as equal in a unique index, Postgres does not.
-- COALESCE(..., 0) gives the same "one row per pair" rule (ids start at 1).
CREATE UNIQUE INDEX "UX_Deps_Pair" ON dev."Dependencies" (
    COALESCE("SourceApplicationId", 0), COALESCE("SourceComponentId", 0),
    COALESCE("TargetApplicationId", 0), COALESCE("TargetComponentId", 0));

-- Architect runs an assessment of one application.
CREATE TABLE dev."Assessments" (
    "AssessmentId"  INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Assessments" PRIMARY KEY,
    "Code"          VARCHAR(20)  GENERATED ALWAYS AS ('ASM-' || RIGHT('000' || CAST("AssessmentId" AS VARCHAR(10)), 3)) STORED,
    "ApplicationId" INTEGER      NOT NULL CONSTRAINT "FK_Assessments_App" REFERENCES dev."Applications" ("ApplicationId"),
    "TechnicalDebt" INTEGER      NOT NULL CONSTRAINT "CK_Asm_TD" CHECK ("TechnicalDebt" BETWEEN 0 AND 100),
    "GovernanceRisk" INTEGER     NOT NULL CONSTRAINT "CK_Asm_GR" CHECK ("GovernanceRisk" BETWEEN 0 AND 100),
    "DependencyImpact" INTEGER   NOT NULL CONSTRAINT "CK_Asm_DI" CHECK ("DependencyImpact" BETWEEN 0 AND 100),
    "AssessedBy"    INTEGER      NOT NULL CONSTRAINT "FK_Assessments_Users" REFERENCES dev."Users" ("UserId"),
    "AssessedAt"    DATE         NOT NULL DEFAULT CAST((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') AS DATE)
);
CREATE INDEX "IX_Assessments_App" ON dev."Assessments" ("ApplicationId", "AssessedAt" DESC);

-- The reason for each point (shown on the Assessments page).
CREATE TABLE dev."AssessmentFactors" (
    "AssessmentFactorId" INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_AssessmentFactors" PRIMARY KEY,
    "AssessmentId"  INTEGER      NOT NULL CONSTRAINT "FK_AsmFactors_Asm" REFERENCES dev."Assessments" ("AssessmentId") ON DELETE CASCADE,
    "ScoreType"     VARCHAR(20)  NOT NULL CONSTRAINT "CK_AsmFactors_Type" CHECK ("ScoreType" IN ('TechnicalDebt', 'GovernanceRisk')),
    "FactorName"    VARCHAR(50)  NOT NULL,      -- Application age
    "FactorValue"   VARCHAR(100) NOT NULL,      -- 14 years
    "Points"        INTEGER      NOT NULL
);

-- What-if: one application + one strategy.
CREATE TABLE dev."Simulations" (
    "SimulationId"  INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Simulations" PRIMARY KEY,
    "Code"          VARCHAR(20)   GENERATED ALWAYS AS ('SIM-' || RIGHT('000' || CAST("SimulationId" AS VARCHAR(10)), 3)) STORED,
    "ApplicationId" INTEGER       NOT NULL CONSTRAINT "FK_Simulations_App" REFERENCES dev."Applications" ("ApplicationId"),
    "AssessmentId"  INTEGER       NOT NULL CONSTRAINT "FK_Simulations_Asm" REFERENCES dev."Assessments" ("AssessmentId"),
    "Strategy"      VARCHAR(12)   NOT NULL CONSTRAINT "CK_Sim_Strategy" CHECK ("Strategy" IN ('Rehost', 'Replatform', 'Refactor', 'Rebuild')),
    "StrategyRisk"  INTEGER       NOT NULL,
    "EmsiScore"     DECIMAL(5,2)  NULL,          -- enterprise EMSI at the time of the simulation
    "ModernizationRisk" INTEGER   NOT NULL CONSTRAINT "CK_Sim_MR" CHECK ("ModernizationRisk" BETWEEN 0 AND 100),
    "RiskLevel"     VARCHAR(6)    GENERATED ALWAYS AS (CASE WHEN "ModernizationRisk" >= 70 THEN 'High' WHEN "ModernizationRisk" >= 40 THEN 'Medium' ELSE 'Low' END) STORED,
    "EffortWeeks"   INTEGER       NOT NULL CONSTRAINT "CK_Sim_Effort" CHECK ("EffortWeeks" > 0),
    "TeamSize"      INTEGER       NOT NULL CONSTRAINT "CK_Sim_Team" CHECK ("TeamSize" BETWEEN 1 AND 50),
    "CostLakh"      DECIMAL(10,2) NOT NULL CONSTRAINT "CK_Sim_Cost" CHECK ("CostLakh" >= 0),   -- in Rs lakh
    "Recommendation" VARCHAR(500) NULL,
    "CreatedBy"     INTEGER       NOT NULL CONSTRAINT "FK_Simulations_Users" REFERENCES dev."Users" ("UserId"),
    "CreatedAt"     DATE          NOT NULL DEFAULT CAST((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') AS DATE)
    -- "Discard / Modify" deletes the row (and its impacts), so there is no status column.
);

-- Components / apps affected by a simulation, in migration order.
CREATE TABLE dev."SimulationImpacts" (
    "SimulationImpactId" INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_SimulationImpacts" PRIMARY KEY,
    "SimulationId"  INTEGER      NOT NULL CONSTRAINT "FK_SimImpacts_Sim" REFERENCES dev."Simulations" ("SimulationId") ON DELETE CASCADE,
    "SequenceNo"    INTEGER      NOT NULL,
    "AffectedName"  VARCHAR(100) NOT NULL,
    "AffectedType"  VARCHAR(12)  NOT NULL CONSTRAINT "CK_SimImpacts_Type" CHECK ("AffectedType" IN ('Application', 'Service', 'API', 'Database')),
    "Criticality"   VARCHAR(10)  NOT NULL,
    "OwnerName"     VARCHAR(100) NULL
);

-- A plan is made from exactly one simulation. Draft -> Submitted -> Approved / Rejected.
CREATE TABLE dev."Plans" (
    "PlanId"        INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Plans" PRIMARY KEY,
    "Code"          VARCHAR(20)  GENERATED ALWAYS AS ('PLAN-' || RIGHT('000' || CAST("PlanId" AS VARCHAR(10)), 3)) STORED,
    "SimulationId"  INTEGER      NOT NULL CONSTRAINT "FK_Plans_Sim" REFERENCES dev."Simulations" ("SimulationId"),
    "PlanName"      VARCHAR(150) NOT NULL CONSTRAINT "CK_Plans_Name" CHECK (LENGTH(RTRIM("PlanName")) >= 3),
    "Status"        VARCHAR(10)  NOT NULL DEFAULT 'Draft'
                                 CONSTRAINT "CK_Plans_Status" CHECK ("Status" IN ('Draft', 'Submitted', 'Approved', 'Rejected')),
    "Notes"         VARCHAR(1000) NULL,
    "CreatedBy"     INTEGER      NOT NULL CONSTRAINT "FK_Plans_CreatedBy" REFERENCES dev."Users" ("UserId"),
    "CreatedAt"     DATE         NOT NULL DEFAULT CAST((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') AS DATE),
    "SubmittedAt"   DATE         NULL,
    "DecidedBy"     INTEGER      NULL CONSTRAINT "FK_Plans_DecidedBy" REFERENCES dev."Users" ("UserId"),   -- Executive
    "DecidedAt"     DATE         NULL,
    "ExecutiveComment" VARCHAR(500) NULL,
    -- a rejected plan must have a reason; a decided plan must say who decided
    CONSTRAINT "CK_Plans_RejectReason" CHECK ("Status" <> 'Rejected' OR LENGTH(RTRIM(COALESCE("ExecutiveComment", ''))) > 0),
    CONSTRAINT "CK_Plans_Decided" CHECK ("Status" NOT IN ('Approved', 'Rejected') OR "DecidedBy" IS NOT NULL),
    CONSTRAINT "CK_Plans_Submitted" CHECK ("Status" = 'Draft' OR "SubmittedAt" IS NOT NULL),
    CONSTRAINT "UQ_Plans_Sim" UNIQUE ("SimulationId"),
    CONSTRAINT "UQ_Plans_Name" UNIQUE ("PlanName")
);

CREATE TABLE dev."PlanPhases" (
    "PlanPhaseId"   INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_PlanPhases" PRIMARY KEY,
    "PlanId"        INTEGER      NOT NULL CONSTRAINT "FK_PlanPhases_Plans" REFERENCES dev."Plans" ("PlanId") ON DELETE CASCADE,
    "PhaseNo"       INTEGER      NOT NULL CONSTRAINT "CK_PlanPhases_No" CHECK ("PhaseNo" BETWEEN 1 AND 10),
    "PhaseName"     VARCHAR(100) NOT NULL,
    "Weeks"         INTEGER      NOT NULL CONSTRAINT "CK_PlanPhases_Weeks" CHECK ("Weeks" >= 0),
    CONSTRAINT "UQ_PlanPhases" UNIQUE ("PlanId", "PhaseNo")
);

