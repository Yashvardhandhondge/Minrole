    "TotalApps"     INTEGER       NOT NULL CONSTRAINT "CK_Cls_Apps" CHECK ("TotalApps" BETWEEN 1 AND 10000),
    "Dependencies"  INTEGER       NOT NULL CONSTRAINT "CK_Cls_Deps" CHECK ("Dependencies" >= 0),
    "Apis"          INTEGER       NOT NULL CONSTRAINT "CK_Cls_Apis" CHECK ("Apis" >= 0),
    "DatabaseCount" INTEGER       NOT NULL CONSTRAINT "CK_Cls_Dbs"  CHECK ("DatabaseCount" >= 0),
    "StorageGB"     INTEGER       NOT NULL CONSTRAINT "CK_Cls_Stor" CHECK ("StorageGB" >= 0),
    "Environments"  INTEGER       NOT NULL CONSTRAINT "CK_Cls_Envs" CHECK ("Environments" BETWEEN 1 AND 20),
    "BusinessUnits" INTEGER       NOT NULL CONSTRAINT "CK_Cls_Units" CHECK ("BusinessUnits" >= 1),
    "UserCount"     INTEGER       NOT NULL CONSTRAINT "CK_Cls_Users" CHECK ("UserCount" >= 1),
