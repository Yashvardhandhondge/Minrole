    "AssignableScope" VARCHAR(100) NOT NULL,      -- rg-webapp-prod
    "IncludeBaselineRead" BOOLEAN  NOT NULL DEFAULT TRUE,
    "IsReviewed"      BOOLEAN      NOT NULL DEFAULT FALSE,
    "ReviewedBy"      INTEGER      NULL     CONSTRAINT "FK_GenRoles_Users" REFERENCES dev."Users" ("UserId"),
    "ReviewedAt"      TIMESTAMPTZ  NULL,
    CONSTRAINT "UQ_GenRoles" UNIQUE ("AnalysisId", "IdentityId")
