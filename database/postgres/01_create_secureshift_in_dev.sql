    "RuleSettingId"       INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_RuleSettings" PRIMARY KEY,
    "WeightUnused"        INTEGER NOT NULL CONSTRAINT "CK_Rules_W1" CHECK ("WeightUnused" BETWEEN 0 AND 100),
    "WeightHighRisk"      INTEGER NOT NULL CONSTRAINT "CK_Rules_W2" CHECK ("WeightHighRisk" BETWEEN 0 AND 100),
    "WeightScope"         INTEGER NOT NULL CONSTRAINT "CK_Rules_W3" CHECK ("WeightScope" BETWEEN 0 AND 100),
