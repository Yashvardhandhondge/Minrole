/* =====================================================================
   SecureShift - 01_create_secureshift_in_dev.sql
   PostgreSQL version of database/01_create_schema.sql (SQL Server).

   Creates the 28 SecureShift tables and 4 views inside the EXISTING
   schema "dev" (auth / gov / emdt are not separate schemas in Postgres).

   Safe by design:
     - ONE transaction: either everything is created or nothing is.
     - NO "CREATE SCHEMA" and NO "DROP": the schema dev must already exist.
     - Plain CREATE TABLE / CREATE VIEW (no IF NOT EXISTS, no OR REPLACE):
       if any name already exists, the script FAILS and nothing is changed.

   How to run (psql):
     psql "<connection>" -v ON_ERROR_STOP=1 -f 01_create_secureshift_in_dev.sql
   Or with the console:  dotnet run --project src/SecureShift.Console -- db setup

   Conversion rules used (syntax only, every table / column / key / CHECK / view kept):
     IDENTITY(1,1)              -> GENERATED BY DEFAULT AS IDENTITY
     BIT                        -> BOOLEAN
     DATETIME2 / SYSUTCDATETIME -> TIMESTAMPTZ / CURRENT_TIMESTAMP
     computed columns           -> GENERATED ALWAYS AS (...) STORED
     LIKE '[...]' patterns      -> regex CHECKs (~)
     DATEDIFF(DAY, a, b)        -> (b - a)        (date minus date = days)
     LEN(x)                     -> LENGTH(RTRIM(x)) (LEN ignores trailing spaces)
     ISNULL                     -> COALESCE
     UX_Deps_Pair (NULLs equal in SQL Server) -> COALESCE expression index
   Postgres has no named DEFAULT constraints, so the DF_* names are gone
   (the default values themselves are kept).
   ===================================================================== */

