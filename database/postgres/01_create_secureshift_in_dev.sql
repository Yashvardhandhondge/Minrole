-- The 5 roles. Product says which module the role belongs to.
CREATE TABLE dev."Roles" (
    "RoleId"      INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Roles" PRIMARY KEY,
    "RoleCode"    VARCHAR(20)  NOT NULL,   -- cloudadmin, superadmin ...
    "RoleName"    VARCHAR(50)  NOT NULL,   -- Cloud Admin, Super Admin ...
    "Product"     VARCHAR(20)  NOT NULL CONSTRAINT "CK_Roles_Product" CHECK ("Product" IN ('Governance', 'Modernization')),
    "HomePage"    VARCHAR(100) NOT NULL,   -- dashboard opened after login
    CONSTRAINT "UQ_Roles_Code" UNIQUE ("RoleCode"),
    CONSTRAINT "UQ_Roles_Name" UNIQUE ("RoleName")
);

-- Everyone who can log in (both modules).
CREATE TABLE dev."Users" (
    "UserId"      INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Users" PRIMARY KEY,
    "Code"        VARCHAR(20)  GENERATED ALWAYS AS ('USR-' || RIGHT('000' || CAST("UserId" AS VARCHAR(10)), 3)) STORED,
    "FullName"    VARCHAR(50)  NOT NULL CONSTRAINT "CK_Users_Name"  CHECK (LENGTH(RTRIM("FullName")) >= 3 AND "FullName" ~ '^[A-Za-z ]*$'),
    "Email"       VARCHAR(150) NOT NULL CONSTRAINT "CK_Users_Email" CHECK ("Email" LIKE '_%@_%._%'),
    "Phone"       CHAR(10)     NULL     CONSTRAINT "CK_Users_Phone" CHECK ("Phone" ~ '^[6-9][0-9]{9}$'),
    "PasswordHash" VARCHAR(256) NOT NULL,                -- never store the plain password
    "RoleId"      INTEGER      NOT NULL CONSTRAINT "FK_Users_Roles" REFERENCES dev."Roles" ("RoleId"),
    "Department"  VARCHAR(150) NULL     CONSTRAINT "CK_Users_Dept"  CHECK ("Department" IS NULL OR (LENGTH(RTRIM("Department")) >= 3 AND "Department" ~ '^[A-Za-z0-9 ]*$')),
    "Status"      VARCHAR(10)  NOT NULL DEFAULT 'Active'     -- new users are always Active
                               CONSTRAINT "CK_Users_Status" CHECK ("Status" IN ('Active', 'Inactive')),
    "MustChangePassword" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "CreatedBy"   INTEGER      NULL     CONSTRAINT "FK_Users_CreatedBy" REFERENCES dev."Users" ("UserId"),
    "LastLoginAt" TIMESTAMPTZ  NULL,
    CONSTRAINT "UQ_Users_Email" UNIQUE ("Email")
);
CREATE INDEX "IX_Users_Role" ON dev."Users" ("RoleId");

-- Every important action (Super Admin > Audit Logs page).
CREATE TABLE dev."AuditLogs" (
    "AuditLogId"  INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_AuditLogs" PRIMARY KEY,
    "UserId"      INTEGER      NOT NULL CONSTRAINT "FK_AuditLogs_Users" REFERENCES dev."Users" ("UserId"),  -- who did it
    "Action"      VARCHAR(50)  NOT NULL,     -- User Created, Role Changed, Plan Approved ...
    "Target"      VARCHAR(150) NULL,         -- what it was done to
    "Detail"      VARCHAR(500) NULL,
    "CreatedAt"   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "IX_AuditLogs_Created" ON dev."AuditLogs" ("CreatedAt" DESC);

/* =====================================================================
   GOV  - Cloud Governance
   Flow: Company -> Analysis (fixed period) -> Identity scores, Findings,
         Generated roles -> Report
   ===================================================================== */

-- Each Azure tenant (customer company) we analyse.
CREATE TABLE dev."Companies" (
    "CompanyId"     INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Companies" PRIMARY KEY,
    "CompanyName"   VARCHAR(100) NOT NULL CONSTRAINT "CK_Companies_Name" CHECK (LENGTH(RTRIM("CompanyName")) >= 3),
    "TenantId"      VARCHAR(36)  NULL,       -- Azure AD tenant GUID
    "Subscriptions" INTEGER      NOT NULL DEFAULT 1 CONSTRAINT "CK_Companies_Subs" CHECK ("Subscriptions" BETWEEN 1 AND 500),
    "CreatedBy"     INTEGER      NULL     CONSTRAINT "FK_Companies_Users" REFERENCES dev."Users" ("UserId"),
    "CreatedAt"     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "UQ_Companies_Name" UNIQUE ("CompanyName")
);

-- One run of the 4-step Analysis Wizard, always on a fixed period (7-180 days).
CREATE TABLE dev."Analyses" (
    "AnalysisId"    INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Analyses" PRIMARY KEY,
    "Code"          VARCHAR(20)  NOT NULL,   -- AN-2026-1110
    "CompanyId"     INTEGER      NOT NULL CONSTRAINT "FK_Analyses_Companies" REFERENCES dev."Companies" ("CompanyId"),
    "PeriodFrom"    DATE         NOT NULL,
    "PeriodTo"      DATE         NOT NULL,
    "PeriodDays"    INTEGER      GENERATED ALWAYS AS (("PeriodTo" - "PeriodFrom") + 1) STORED,
    "Status"        VARCHAR(12)  NOT NULL DEFAULT 'Running'
                                 CONSTRAINT "CK_Analyses_Status" CHECK ("Status" IN ('Running', 'Complete', 'Failed')),
    "IdentityCount" INTEGER      NULL,
    "AvgScore"      DECIMAL(5,2) NULL,
    "HighRiskCount" INTEGER      NULL,
    "RunBy"         INTEGER      NOT NULL CONSTRAINT "FK_Analyses_Users" REFERENCES dev."Users" ("UserId"),
    "RunAt"         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "CK_Analyses_Period" CHECK (("PeriodTo" - "PeriodFrom") + 1 BETWEEN 7 AND 180),
    CONSTRAINT "UQ_Analyses_Code" UNIQUE ("Code")
);
CREATE INDEX "IX_Analyses_Company" ON dev."Analyses" ("CompanyId", "RunAt" DESC);

-- Azure identities: users, service principals, managed identities.
CREATE TABLE dev."Identities" (
    "IdentityId"    INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Identities" PRIMARY KEY,
    "CompanyId"     INTEGER      NOT NULL CONSTRAINT "FK_Identities_Companies" REFERENCES dev."Companies" ("CompanyId"),
    "UserName"      VARCHAR(100) NOT NULL,      -- rahul.verma, svc-webapp-deploy
    "DisplayName"   VARCHAR(100) NOT NULL,      -- Rahul Verma (shown on every screen)
    "IdentityType"  VARCHAR(20)  NOT NULL CONSTRAINT "CK_Identities_Type" CHECK ("IdentityType" IN ('User', 'Service Principal', 'Managed Identity')),
    "AssignedRole"  VARCHAR(50)  NOT NULL,      -- Owner, Contributor, Reader ...
    "Scope"         VARCHAR(30)  NOT NULL CONSTRAINT "CK_Identities_Scope" CHECK ("Scope" IN ('Management Group', 'Subscription', 'Resource Group', 'Resource')),
    "ScopeName"     VARCHAR(100) NULL,         -- rg-sales (NULL when the scope is the whole subscription)
    CONSTRAINT "UQ_Identities_UserName" UNIQUE ("CompanyId", "UserName")
);

-- The score of one identity in one analysis (scores change from run to run).
CREATE TABLE dev."IdentityScores" (
    "IdentityScoreId"   INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_IdentityScores" PRIMARY KEY,
    "AnalysisId"        INTEGER NOT NULL CONSTRAINT "FK_IdentityScores_Analyses" REFERENCES dev."Analyses" ("AnalysisId"),
    "IdentityId"        INTEGER NOT NULL CONSTRAINT "FK_IdentityScores_Identities" REFERENCES dev."Identities" ("IdentityId"),
    "GrantedCount"      INTEGER NOT NULL CONSTRAINT "CK_IdentityScores_Granted" CHECK ("GrantedCount" >= 0),
    "UsedCount"         INTEGER NOT NULL CONSTRAINT "CK_IdentityScores_Used"    CHECK ("UsedCount" >= 0),
    "UnusedHighRisk"    INTEGER NOT NULL DEFAULT 0,
    "RiskScore"         INTEGER NOT NULL CONSTRAINT "CK_IdentityScores_Score"   CHECK ("RiskScore" BETWEEN 0 AND 100),
    "RiskLevel"         VARCHAR(6) GENERATED ALWAYS AS (CASE WHEN "RiskScore" >= 70 THEN 'HIGH' WHEN "RiskScore" >= 40 THEN 'MEDIUM' ELSE 'LOW' END) STORED,
    "SuggestedScope"    VARCHAR(100) NULL,       -- rg-webapp-prod
    CONSTRAINT "UQ_IdentityScores" UNIQUE ("AnalysisId", "IdentityId"),
    CONSTRAINT "CK_IdentityScores_UsedLeGranted" CHECK ("UsedCount" <= "GrantedCount")
);

-- Evidence: which permissions an identity really used in the period.
CREATE TABLE dev."PermissionUsage" (
    "PermissionUsageId" INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_PermissionUsage" PRIMARY KEY,
    "AnalysisId"        INTEGER      NOT NULL CONSTRAINT "FK_PermUsage_Analyses" REFERENCES dev."Analyses" ("AnalysisId"),
    "IdentityId"        INTEGER      NOT NULL CONSTRAINT "FK_PermUsage_Identities" REFERENCES dev."Identities" ("IdentityId"),
    "Action"            VARCHAR(200) NOT NULL,   -- Microsoft.Web/sites/write
    "FirstUsed"         DATE         NOT NULL,
    "LastUsed"          DATE         NOT NULL,
    "EventCount"        INTEGER      NOT NULL CONSTRAINT "CK_PermUsage_Events" CHECK ("EventCount" > 0),
    "ResourceGroup"     VARCHAR(100) NULL
);
CREATE INDEX "IX_PermUsage_Identity" ON dev."PermissionUsage" ("AnalysisId", "IdentityId");

-- High-risk permissions that were granted but never used (read-only, no Revoke).
CREATE TABLE dev."Findings" (
    "FindingId"     INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Findings" PRIMARY KEY,
    "Code"          VARCHAR(20)  GENERATED ALWAYS AS ('F-' || CAST("FindingId" AS VARCHAR(10))) STORED,
    "AnalysisId"    INTEGER      NOT NULL CONSTRAINT "FK_Findings_Analyses" REFERENCES dev."Analyses" ("AnalysisId"),
    "IdentityId"    INTEGER      NOT NULL CONSTRAINT "FK_Findings_Identities" REFERENCES dev."Identities" ("IdentityId"),
    "Action"        VARCHAR(200) NOT NULL,
    "Category"      VARCHAR(20)  NOT NULL CONSTRAINT "CK_Findings_Category" CHECK ("Category" IN ('Delete', 'Network', 'Key Vault', 'Role Assignment')),
    "Severity"      VARCHAR(10)  NOT NULL CONSTRAINT "CK_Findings_Severity" CHECK ("Severity" IN ('HIGH', 'MEDIUM', 'LOW')),
    "GrantedByRole" VARCHAR(50)  NOT NULL,
    "LastUsed"      DATE         NULL,          -- NULL = never used
    "Status"        VARCHAR(10)  NOT NULL DEFAULT 'Open'
